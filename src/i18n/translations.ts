export function t(
  key: string,
  lang: Language,
  params?: Record<string, string | number>
): string {
  const keys = key.split(".");
  let value: any = translations[lang];

  for (const k of keys) {
    value = value?.[k];
  }

  if (typeof value !== "string") {
    return key;
  }

  if (params) {
    return value.replace(/{(\w+)}/g, (_, param) => String(params[param] ?? ""));
  }

  return value;
}